# Создает прямую ссылку на ячейку листа "Инструкции" без использования именованных диапазонов.
function Add-InstructionHyperlink {
    param([object]$Cell, [string]$SheetName, [int]$TargetRow)
    $Cell.Hyperlinks.Delete()
